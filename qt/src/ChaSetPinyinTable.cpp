const PinyinSyllable *lookupSyllable(uint32_t codePoint) {
  if (codePoint < kPinyinTableStart || codePoint > kPinyinTableEnd) {
    return nullptr;
  }
  const uint16_t idx = kCodePointToSyllable[codePoint - kPinyinTableStart];
  if (idx == 0 || idx >= sizeof(kSyllables) / sizeof(kSyllables[0])) {
    return nullptr;
  }
  return &kSyllables[idx];
}

