/**
 * Renders status icon matching the given pipeline status with automatic spin animation.
 */
export function StatusIcon({
  status,
  className,
}: {
  status: AnyPipelineStatus;
  className?: string;
}) {
  const norm = normalizeStatus(status);
  const spinning = isSpinningStatus(status);
  const baseClass = cn(spinning && 'animate-spin', className);

  switch (norm) {
    case 'queued':
      return <CircleDashedIcon className={baseClass} />;
    case 'compiling':
    case 'running':
      return <Loader2Icon className={baseClass} />;
    case 'retrying':
      return <RotateCwIcon className={baseClass} />;
    case 'success':
      return <CircleCheckIcon className={baseClass} />;
    case 'failure':
      return <CircleXIcon className={baseClass} />;
    case 'cancelled':
      return <MinusIcon className={baseClass} />;
  }
}
